let pages = [];
let currentPage = 0;
let isTurning = false;

const beginButton = document.getElementById("begin-story");
const bookCover = document.querySelector(".book-cover");

beginButton.addEventListener("click", openBook);

function openBook() {
    bookCover.classList.add("opening");

    setTimeout(() => {
        showReader();
    }, 700);
}

function showReader() {
    document.body.innerHTML = `
        <main class="reader">
            <div class="page-stage">
                <section class="page" id="book-page">
                    <div class="paper-text" id="page-content"></div>
                    <span class="printed-page-number" id="printed-page-number"></span>
                </section>
            </div>

            <nav class="reader-navigation" aria-label="Book navigation">
                <button type="button" id="previous-page" aria-label="Previous page">
                    ← Previous
                </button>

                <button type="button" id="next-page" aria-label="Next page">
                    Next →
                </button>
            </nav>
        </main>

        <div class="pagination-measurement" aria-hidden="true">
            <div class="paper-text" id="measurement-content"></div>
        </div>
    `;

    document.getElementById("previous-page").addEventListener("click", previousPage);
    document.getElementById("next-page").addEventListener("click", nextPage);
    document.addEventListener("keydown", handleKeyboard);

    requestAnimationFrame(() => {
        pages = paginateStory();
        currentPage = 0;
        renderPage(false);
    });
}

function createBlockElement(block, textOverride = null) {
    const text = textOverride ?? block.text;
    let element;

    if (block.type === "heading") {
        element = document.createElement("h1");
        element.className = "original-heading";
        element.textContent = text;
        return element;
    }

    element = document.createElement("p");
    element.textContent = text;

    if (block.type === "picture") {
        element.className = "picture-placeholder";
        element.style.minHeight = "150px";
        element.style.display = "flex";
        element.style.alignItems = "center";
        element.style.justifyContent = "center";
        element.style.margin = "22px 0";
        element.style.border = "1px dashed rgba(128, 109, 80, 0.65)";
        element.style.textAlign = "center";
        element.style.fontStyle = "italic";
        element.style.color = "#806d50";
    }

    return element;
}

function paginateStory() {
    const measurement = document.getElementById("measurement-content");
    const generatedPages = [];
    let currentPageBlocks = [];

    measurement.innerHTML = "";

    function saveCurrentPage() {
        if (currentPageBlocks.length === 0) return;

        generatedPages.push(currentPageBlocks.map(item => ({
            block: item.block,
            text: item.text
        })));

        currentPageBlocks = [];
        measurement.innerHTML = "";
    }

    storyBlocks.forEach(block => {
        const fullElement = createBlockElement(block);
        measurement.appendChild(fullElement);

        if (!isOverflowing(measurement)) {
            currentPageBlocks.push({ block, text: block.text });
            return;
        }

        measurement.removeChild(fullElement);

        if (block.type !== "paragraph") {
            saveCurrentPage();
            measurement.appendChild(createBlockElement(block));
            currentPageBlocks.push({ block, text: block.text });
            return;
        }

        let remainingWords = block.text.split(/\s+/);

        while (remainingWords.length > 0) {
            const wordsThatFit = findWordsThatFit(measurement, block, remainingWords);

            if (wordsThatFit === 0) {
                saveCurrentPage();
                continue;
            }

            const pageText = remainingWords.slice(0, wordsThatFit).join(" ");
            measurement.appendChild(createBlockElement(block, pageText));
            currentPageBlocks.push({ block, text: pageText });
            remainingWords = remainingWords.slice(wordsThatFit);

            if (remainingWords.length > 0) saveCurrentPage();
        }
    });

    saveCurrentPage();
    return generatedPages;
}

function findWordsThatFit(container, block, words) {
    let low = 1;
    let high = words.length;
    let bestFit = 0;

    while (low <= high) {
        const middle = Math.floor((low + high) / 2);
        const testText = words.slice(0, middle).join(" ");
        const testElement = createBlockElement(block, testText);
        container.appendChild(testElement);

        if (!isOverflowing(container)) {
            bestFit = middle;
            low = middle + 1;
        } else {
            high = middle - 1;
        }

        container.removeChild(testElement);
    }

    return bestFit;
}

function isOverflowing(element) {
    return element.scrollHeight > element.clientHeight + 1;
}

function displayCurrentPage() {
    const content = document.getElementById("page-content");
    content.innerHTML = "";

    pages[currentPage].forEach(item => {
        content.appendChild(createBlockElement(item.block, item.text));
    });

    document.getElementById("printed-page-number").textContent = currentPage + 1;
    document.getElementById("previous-page").disabled = false;
    document.getElementById("next-page").disabled = currentPage === pages.length - 1;
}

function renderPage(animate = true, direction = "forward") {
    if (isTurning || pages.length === 0) return;

    const pageElement = document.getElementById("book-page");

    if (!animate) {
        displayCurrentPage();
        return;
    }

    isTurning = true;

    const outClass = direction === "forward"
        ? "page-turn-forward-out"
        : "page-turn-back-out";

    const inClass = direction === "forward"
        ? "page-turn-forward-in"
        : "page-turn-back-in";

    pageElement.classList.add(outClass);

    setTimeout(() => {
        displayCurrentPage();
        pageElement.classList.remove(outClass);
        pageElement.classList.add(inClass);

        setTimeout(() => {
            pageElement.classList.remove(inClass);
            isTurning = false;
        }, 380);
    }, 320);
}

function nextPage() {
    if (currentPage >= pages.length - 1 || isTurning) return;
    currentPage++;
    renderPage(true, "forward");
}

function previousPage() {
    if (isTurning) return;

    if (currentPage === 0) {
        window.location.reload();
        return;
    }

    currentPage--;
    renderPage(true, "back");
}

function handleKeyboard(event) {
    if (event.key === "ArrowRight") nextPage();
    if (event.key === "ArrowLeft") previousPage();
    if (event.key === "Home") window.location.reload();
}
